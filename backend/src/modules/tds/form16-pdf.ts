/** Form 16 (Part A + Part B summary) as a one-page PDF. */
import { SimplePdfDocument } from '../payroll-outputs/index.js';
import type { form16 } from './tds.service.js';

const inr = (n: number) => `Rs ${n.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

export function renderForm16Pdf(f: Awaited<ReturnType<typeof form16>>): Buffer {
  const doc = new SimplePdfDocument();
  let y = 800;
  const line = (text: string, opts: { x?: number; size?: number; bold?: boolean } = {}) => {
    doc.drawText({ text, x: opts.x ?? 40, y, fontSize: opts.size ?? 10, bold: opts.bold ?? false });
    y -= (opts.size ?? 10) + 6;
  };
  line('FORM No. 16', { size: 16, bold: true });
  line(`Certificate under section 203 of the Income-tax Act, 1961 for tax deducted at source on salary — FY ${f.fy} (AY ${f.assessmentYear})`, { size: 8 });
  y -= 6;
  line('PART A', { bold: true, size: 12 });
  line(`Employer: ${f.employer.name}   TAN: ${f.employer.tan ?? 'NOT SET'}   PAN: ${f.employer.pan ?? 'NOT SET'}`);
  if (f.employer.address) line(`Address: ${f.employer.address}`, { size: 8 });
  line(`Employee: ${f.employee.name} (${f.employee.ecode})   PAN: ${f.employee.pan ?? 'PANNOTAVBL'}`);
  y -= 4;
  line('Quarter      Amount paid/credited          Tax deducted', { bold: true });
  for (const q of f.partA.quarters) line(`Q${String(q.quarter)}           ${inr(q.amountPaidRupees).padEnd(30)}${inr(q.tdsRupees)}`);
  line(`Total TDS deducted and deposited: ${inr(f.partA.totalTdsRupees)}`, { bold: true });
  y -= 8;
  line('PART B (Annexure) — details of salary and tax', { bold: true, size: 12 });
  line(`Tax regime: ${f.employee.regime === 'new' ? 'New (s.115BAC)' : 'Old'}`);
  line(`1. Gross salary: ${inr(f.partB.grossSalaryRupees)}`);
  line(`2. Standard deduction u/s 16(ia): ${inr(f.partB.standardDeductionRupees)}`);
  for (const d of f.partB.deductions) line(`   Chapter VI-A ${d.section}: claimed ${inr(d.claimedRupees)}, allowed ${inr(d.allowedRupees)}`, { size: 9 });
  line(`3. Total Chapter VI-A deductions: ${inr(f.partB.chapterViaRupees)}`);
  line(`4. Total taxable income: ${inr(f.partB.taxableIncomeRupees)}`, { bold: true });
  y -= 10;
  line('Generated by Rashmi HRMS from finalized payroll. Verify against TRACES Form 16 Part A before issue.', { size: 7 });
  return doc.build();
}
